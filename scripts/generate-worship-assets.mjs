import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const manifestPath = path.join(root, "public/tool/worship-songs/asset-manifest.json");
const galleryPath = path.join(
  root,
  "components/worship-songs/features/song-viewer/lib/gallery.js",
);

const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const gallery = Object.fromEntries(
  Object.entries(manifest.files)
    .filter(([source, output]) => source.endsWith(".webp") && output.endsWith(".webp"))
    .map(([source, output]) => [path.basename(source, ".webp"), output])
    .sort(([left], [right]) => left.localeCompare(right, "en", { numeric: true })),
);

fs.writeFileSync(
  galleryPath,
  `// Generated by scripts/generate-worship-assets.mjs.\nconst gallery = ${JSON.stringify(gallery, null, 2)};\n\nexport default gallery;\n`,
  "utf8",
);

console.log(`Generated worship-song gallery with ${Object.keys(gallery).length} sheet pages.`);
